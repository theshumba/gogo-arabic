/**
 * Helper: Get all recipes for a specific profession
 */
export function getRecipesByProfession(professionId) {
  return Object.values(RECIPES).filter(recipe => recipe.professionId === professionId);
}

/**
 * Helper: Get all recipes unlockable at or below a specific level for a profession
 */
export function getRecipesByLevel(professionId, level) {
  return Object.values(RECIPES).filter(
    recipe => recipe.professionId === professionId && recipe.minLevel <= level
  );
}
