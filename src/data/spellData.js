/**
 * Get spell by root ID and form
 * @param {string} rootId - Hyphen-separated Arabic root
 * @param {string} form - Verb form (I-X)
 * @returns {object|null} Spell object or null if not found
 */
export function getSpellByRoot(rootId, form = 'I') {
  // Currently all spells are Form I
  // TODO: Generate higher form variants dynamically or add them to SPELLS array
  return SPELLS.find((s) => s.rootId === rootId && s.form === form) || null;
}

/**
 * Get all spells for a given element
 * @param {string} element - Element name
 * @returns {object[]} Array of spells
 */
export function getSpellsByElement(element) {
  return SPELLS.filter((s) => s.element === element);
}

/**
 * Get tier information for a spell
 * @param {object} spell - Spell object
 * @returns {object} SPELL_TIERS entry
 */
export function getSpellTier(spell) {
  return SPELL_TIERS[spell.form] || SPELL_TIERS.I;
}
