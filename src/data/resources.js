/**
 * Helper: Get all resources that can be found in a specific zone
 */
export function getResourcesByZone(zoneId) {
  return Object.values(RESOURCES).filter(resource =>
    resource.zones.includes(zoneId)
  );
}

/**
 * Helper: Get all resources used by a specific profession
 */
export function getResourcesByProfession(professionId) {
  return Object.values(RESOURCES).filter(resource =>
    resource.professions.includes(professionId)
  );
}
