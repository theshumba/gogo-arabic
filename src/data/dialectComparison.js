export const DIALECT_CATEGORIES = ["greetings","food","body","family","animals","clothing","colors","house","nature","numbers","verbs","adjectives","places","time"];

export function getWordsByCategory(category) {
  return DIALECT_COMPARISON.filter((w) => w.category === category);
}

export function getDialectWord(wordId, dialect) {
  const word = DIALECT_COMPARISON.find((w) => w.id === wordId);
  if (!word) return null;
  return word[dialect] || word.msa;
}
