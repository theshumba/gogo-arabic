/** Lookup by ID (O(1) via Map) */
const _byId = new Map(ARABIC_IDIOMS.map((i) => [i.id, i]));
export function getIdiomById(id) {
  return _byId.get(id) ?? null;
}

/** Filter by category */
export function getIdiomsByCategory(category) {
  return ARABIC_IDIOMS.filter((i) => i.category === category);
}

/** Filter by CEFR level */
export function getIdiomsByLevel(cefrLevel) {
  return ARABIC_IDIOMS.filter((i) => i.cefrLevel === cefrLevel);
}

/** Search by Arabic, English (meaning, literal, equiv), or transliteration */
export function searchIdioms(query) {
  if (!query || typeof query !== 'string') return [];
  const q = query.toLowerCase().trim();
  if (!q) return [];

  return ARABIC_IDIOMS.filter((idiom) => {
    return (
      idiom.arabic.includes(q) ||
      idiom.transliteration.toLowerCase().includes(q) ||
      idiom.literal.toLowerCase().includes(q) ||
      idiom.meaning.toLowerCase().includes(q) ||
      idiom.englishEquivalent.toLowerCase().includes(q) ||
      idiom.usageExample.arabic.includes(q) ||
      idiom.usageExample.english.toLowerCase().includes(q)
    );
  });
}

/** Get a random idiom (optional seed for deterministic results) */
export function getRandomIdiom(seed) {
  if (seed !== undefined) {
    const index = Math.abs(seed) % ARABIC_IDIOMS.length;
    return ARABIC_IDIOMS[index];
  }
  const index = Math.floor(Math.random() * ARABIC_IDIOMS.length);
  return ARABIC_IDIOMS[index];
}

/**
 * Alias for getIdiomsByCategory — Redux-selector naming convention.
 * selectIdiomsBy('wisdom') returns all wisdom idioms.
 */
export function selectIdiomsBy(category) {
  return getIdiomsByCategory(category);
}

/**
 * Daily idiom rotation — same date string always returns the same idiom.
 * Uses charcode sum of date string modulo array length.
 *
 * @param {string} dateString - ISO date string, e.g. '2026-04-07'
 * @returns {object} idiom object
 */
export function selectDailyIdiom(dateString) {
  if (!dateString || typeof dateString !== 'string') {
    return ARABIC_IDIOMS[0];
  }
  let hash = 0;
  for (let i = 0; i < dateString.length; i++) {
    hash += dateString.charCodeAt(i);
  }
  return ARABIC_IDIOMS[hash % ARABIC_IDIOMS.length];
}
