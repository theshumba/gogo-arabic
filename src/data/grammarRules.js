// ── Selectors ──────────────────────────────────────────────────────────────

const _rulesById = new Map(GRAMMAR_RULES.map((r) => [r.id, r]));

/**
 * selectRuleById(id) — returns grammar rule by ID, or null.
 */
export function selectRuleById(id) {
  return _rulesById.get(id) ?? null;
}

/**
 * selectRulesByLevel(cefrLevel) — returns all rules for a given CEFR level.
 */
export function selectRulesByLevel(cefrLevel) {
  return GRAMMAR_RULES.filter((r) => r.cefrLevel === cefrLevel);
}

/**
 * selectRulesByCategory(category) — returns all rules for a given category.
 */
export function selectRulesByCategory(category) {
  return GRAMMAR_RULES.filter((r) => r.category === category);
}
