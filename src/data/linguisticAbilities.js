/**
 * Get all abilities of a specific category.
 * @param {'offense'|'defense'|'utility'} category
 * @returns {Object[]}
 */
export function getAbilitiesByCategory(category) {
  return linguisticAbilities.filter((a) => a.category === category);
}

/**
 * Get all abilities powered by a specific skill.
 * @param {string} skill
 * @returns {Object[]}
 */
export function getAbilitiesByPoweredBy(skill) {
  return linguisticAbilities.filter((a) => a.poweredBy === skill);
}

/**
 * Get a single ability by ID.
 * @param {string} id
 * @returns {Object|undefined}
 */
export function getAbilityById(id) {
  return linguisticAbilities.find((a) => a.id === id);
}

