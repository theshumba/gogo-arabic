/**
 * Get a challenge by its week number (1-52).
 * Returns undefined if no challenge exists for that week.
 */
export function getWeeklyChallenge(week) {
  return WEEKLY_CHALLENGES.find((c) => c.week === week);
}

/**
 * Get the challenge for the current calendar week (1-52).
 */
export function getCurrentWeekChallenge() {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 1);
  const dayOfYear = Math.floor((now - startOfYear) / 86400000) + 1;
  const week = Math.min(Math.ceil(dayOfYear / 7), 52);
  return getWeeklyChallenge(week);
}

