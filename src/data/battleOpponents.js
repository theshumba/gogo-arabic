/**
 * Get all opponents for a specific zone.
 * @param {string} zone
 * @returns {Object[]}
 */
export function getOpponentsByZone(zone) {
  return battleOpponents.filter((o) => o.zone === zone);
}

/**
 * Get all opponents of a specific type.
 * @param {string} type
 * @returns {Object[]}
 */
export function getOpponentsByType(type) {
  return battleOpponents.filter((o) => o.type === type);
}

/**
 * Get a single opponent by ID.
 * @param {string} id
 * @returns {Object|undefined}
 */
export function getOpponentById(id) {
  return battleOpponents.find((o) => o.id === id);
}

/** Redux-selector alias */
export function selectOpponentsByZone(zone) {
  return getOpponentsByZone(zone);
}

/** Redux-selector alias */
export function selectOpponentById(id) {
  return getOpponentById(id);
}

